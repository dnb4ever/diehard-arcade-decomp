#!/usr/bin/env python3
"""Generate a pinned convergence hook catalogue and guest layout constants."""
import json,re,hashlib
from pathlib import Path
w=next(p for p in Path(__file__).resolve().parents if (p/'STATE.md').is_file())/'work/p421'; s=w/'snapshot'; out=w/'port/mods/sdk'
rows=json.loads((s/'converge-generated/overrides.json').read_text())
symbols={}; aliases={}
for line in (s/'notes/symbols.txt').read_text().splitlines():
 m=re.match(r'0x(\w{8})\s+(?:0x\w{8}\s+)?([A-Za-z_]\w*)',line)
 if m:
  a,n=m.groups();symbols[a.lower()]=n;aliases.setdefault(a.lower(),[]).append(n)
header=['/* Generated by p421_generate_sdk.py; do not edit. */','#ifndef DH_HOOKS_H','#define DH_HOOKS_H']
cpp=[]
for r in rows:
 a=r['address']; name=symbols.get(a,'func_'+a)
 source=s/'project/src_functional'/f'{a}.c'
 # Prefer the actual readable function definition to historical aliases.
 t=source.read_text() if source.exists() else ''
 defs=re.findall(r'^\w+[\w\s*]*?\s+(\w+)\s*\([^;{}]*\)\s*\{',t,re.M)
 if defs:name=defs[-1]
 names=sorted(set(aliases.get(a,[])+[name,'func_'+a,a,r['pc'].lower()]))
 names=[n for n in names if re.fullmatch(r'[A-Za-z_0-9]+',n)]
 resumable=r['bridge']=='resumable-C'
 # Replacement needs a per-entry contract. Initial mutable result API is fixmul only;
 # other nonpoll replacements must be equivalent and remain checked by adapters.
 replace=not resumable
 r.update(name=name,aliases=names,replacement=replace,pre_post=not resumable,
          contract='round4_contracts_compute.json' if resumable else 'round4_recipes.json + generated adapter',
          result_policy='mutable result; original MACH/MACL/r1 recipe' if a=='022131c8' else 'equivalent result and ordered effects only')
 header.append(f'#define DH_FN_{name} 0x{a}u')
 cpp.append('{"'+name+'","'+'|'.join(names)+f'",0x{a}u,0x{r["pc"]}u,{str(replace).lower()},{str(not resumable).lower()}'+'},')
# Actor layout constants from dh_work.h, names/offsets used in architecture notes.
layout=(s/'project/src_functional/dh_work.h').read_text()
for field in ['slot_id','health','position_x','position_y','position_z']:
 m=re.search(r'\b'+field+r';[^\n]*?/\*\s*([0-9a-f]{2})',layout)
 assert m,field
 header.append(f'#define DH_ACTOR_{field.upper()} 0x{m[1]}u')
header+=['#define DH_ACTOR_SIZE 0x18cu','#define DH_PLAYER_JOIN_STATES 0x06098674u',
         '#define DH_ACTOR_TASK_SLOTS 0x060995b0u','#define DH_SCENE_INDEX 0x06098668u','#endif']
(out/'dh_hooks.h').write_text('\n'.join(header)+'\n')
(out/'hookable.json').write_text(json.dumps(rows,indent=2)+'\n')
(w/'runtime/src/machine/p421_hooks.inc').write_text('\n'.join(cpp)+'\n')
print(len(rows),'qualified entries; eight resumable entries catalogue-only')
